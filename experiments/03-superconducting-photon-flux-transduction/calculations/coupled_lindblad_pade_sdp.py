#!/usr/bin/env python3
"""Published coupled-Lindblad SDP applied to the direct-port Padé BCFs.

Reference
---------
Z. Huang, G. Park, G. K.-L. Chan, L. Lin,
"Coupled Lindblad pseudomode theory for simulating open quantum systems",
arXiv:2506.10308v2 (2026), Theorem 1 and Eq. (8).

For a quasi-Lindblad BCF

    Cq(tau) = l^dag exp(-i Lambda tau) r,

an exactly equivalent coupled Lindblad realization exists if

    Y > 0,
    Y r = l,
    i(Y Lambda - Lambda^dag Y) >= 0.

When exact feasibility fails, Huang et al. prescribe

    min_Y ||l - Y r||_2^2
    s.t. Y > 0,
         i(Y Lambda - Lambda^dag Y) >= 0.

The existing p4/p5/p8 direct-port Padé correlations are known to be globally
non-positive in frequency, so zero residual is impossible.  This calculation
asks a sharper question: how large is the minimum CPTP coupled-mode correction,
and does the corrected BCF remain accurate against the exact physical bath over
0<=tau<=24 and the system-relevant frequency band?

The Padé exponential representation is written

    Cq(tau)=sum_k d_k exp(-z_k tau),
    Lambda_k = -i z_k.

A balanced diagonal quasi-Lindblad factorization is used:

    r_k = sqrt(|d_k|),
    l_k = conj(d_k)/r_k,

so l_k^* r_k=d_k.  Any nonsingular diagonal rescaling is a gauge of the same
diagonal realization; this balanced choice avoids gratuitous conditioning.

Given the SDP solution Y=X^dag X with the positive Hermitian square root X,
we use the theorem's gauge transform

    K = X Lambda X^{-1},
    g = X r,

and define

    H=(K+K^dag)/2,
    Gamma=(K^dag-K)/(2i).

The resulting BCF Cc(tau)=g^dag exp(-i K tau) g is automatically generated by a
coupled Lindblad bath when Gamma>=0.  We compare Cc to both the original Padé BCF
and the exact direct-port correlation.

This is a bath-level feasibility test only.  No system dynamics or Gate-C claim
is made here.
"""
from __future__ import annotations

import math
import numpy as np
from scipy.linalg import expm, eigvalsh
import cvxpy as cp

import heom_fp_harmonic_oracle as fp
from direct_port_bath_correlation import BETA,G,corr_series
from direct_port_pade_spectral_positivity import exact_dimless

S0=2*G/BETA


def balanced_lr(d):
    amp=np.sqrt(np.abs(d))
    if np.any(amp==0):
        raise RuntimeError('zero Padé coefficient not supported in balanced factorization')
    r=amp.astype(complex)
    l=np.conj(d)/amp
    if np.max(np.abs(np.conj(l)*r-d))>1e-12*max(1,np.max(np.abs(d))):
        raise RuntimeError('balanced l/r factorization failed')
    return l,r


def solve_sdp(Lam,l,r):
    n=len(r)
    Y=cp.Variable((n,n),hermitian=True)
    I=np.eye(n)
    # Scale-free strict-positivity floor.  Balanced l/r puts the natural Y scale
    # near unity; 1e-9 is far below the requested physical correction accuracy.
    Q=1j*(Y@Lam - Lam.conj().T@Y)
    Qh=(Q+Q.H)/2
    constraints=[Y >> 1e-9*I, Qh >> 0]
    objective=cp.Minimize(cp.sum_squares(cp.abs(l-Y@r)))
    prob=cp.Problem(objective,constraints)
    installed=cp.installed_solvers()
    solver='CLARABEL' if 'CLARABEL' in installed else 'SCS'
    kwargs=dict(verbose=False)
    if solver=='SCS':
        kwargs.update(eps=2e-9,max_iters=200000)
    prob.solve(solver=solver,**kwargs)
    if Y.value is None:
        raise RuntimeError(f'SDP failed status={prob.status}')
    Yv=np.asarray(Y.value,complex)
    Yv=.5*(Yv+Yv.conj().T)
    residual=float(np.linalg.norm(l-Yv@r))
    rel=residual/max(float(np.linalg.norm(l)),1e-300)
    return Yv,prob.status,float(prob.value),residual,rel,solver


def reconstruct(Lam,r,Y):
    ey,U=np.linalg.eigh(Y)
    if ey.min()<=0:
        raise RuntimeError(f'SDP Y not positive definite: min={ey.min()}')
    X=(U*np.sqrt(ey))@U.conj().T
    Xi=(U*(1/np.sqrt(ey)))@U.conj().T
    K=X@Lam@Xi
    g=X@r
    H=.5*(K+K.conj().T)
    Gamma=(K.conj().T-K)/(2j)
    Gamma=.5*(Gamma+Gamma.conj().T)
    return K,g,H,Gamma,ey


def cq(tau,d,z):
    return np.sum(d*np.exp(-z*tau))


def cc(tau,K,g):
    return np.vdot(g,expm(-1j*K*tau)@g)


def sexp(x,K,g):
    # s(x)=S(omega_c x)/S0 from dimensionless normalized C/(S0 omega_c).
    R=np.linalg.solve(K-x*np.eye(len(g)),g)
    return float(2*np.imag(np.vdot(g,R)))


def exact_corr_norm(tau,wc):
    return corr_series(float(tau)/wc,10000)/(S0*wc)


def audit(N):
    wc,_x,_u,_H,d,z,_ref=fp.harmonic_setup(2,N)
    Lam=np.diag(-1j*z)
    l,r=balanced_lr(d)
    Y,status,obj,res,rel,solver=solve_sdp(Lam,l,r)
    K,g,H,Gamma,ey=reconstruct(Lam,r,Y)
    eG=eigvalsh(Gamma)
    hermH=float(np.linalg.norm(H-H.conj().T,ord='fro'))
    sim_res=float(np.linalg.norm(K-(np.linalg.multi_dot([
        # Reconstruct via X Lambda X^-1 implicitly checked by eigenvalues below.
        np.eye(len(g)),K,np.eye(len(g))
    ])),ord='fro'))
    eig_lam=np.sort_complex(np.diag(Lam))
    eig_k=np.sort_complex(np.linalg.eigvals(K))
    eig_match=float(np.max(np.abs(eig_k-eig_lam)))

    print(f'SDP p{N} n={len(d)} solver={solver} status={status} objective={obj:.12e} '
          f'residual={res:.12e} rel_residual={rel:.12e}',flush=True)
    print(f'PHYSICAL p{N} Ymin={ey.min():.12e} Ymax={ey.max():.12e} condY={ey.max()/ey.min():.6e} '
          f'Gamma_min={eG.min():+.12e} Gamma_max={eG.max():+.12e} '
          f'HermH={hermH:.3e} eig_similarity_err={eig_match:.3e}',flush=True)

    # Time-domain BCF comparisons.
    taus=np.array([0.,.05,.1,.25,.5,1.,2.,4.,8.,12.,16.,20.,24.])
    err_q=[]; err_exact=[]; abs_exact=[]
    for tau in taus:
        qv=cq(tau,d,z); cv=cc(tau,K,g); ex=exact_corr_norm(tau,wc)
        eq=abs(cv-qv)/max(abs(qv),1e-14)
        ee=abs(cv-ex)/max(abs(ex),1e-14)
        err_q.append(eq); err_exact.append(ee); abs_exact.append(abs(cv-ex))
        print(f'CORR p{N} tau={tau:5.2f} coupled=({cv.real:+.12e}{cv.imag:+.12e}j) '
              f'pade=({qv.real:+.12e}{qv.imag:+.12e}j) '
              f'exact=({ex.real:+.12e}{ex.imag:+.12e}j) '
              f'rel_to_pade={eq:.6e} rel_to_exact={ee:.6e}',flush=True)

    # Globally scan coupled spectrum and compare exact over relevant band.
    xcore=np.linspace(-12,20,6401)
    sc=np.array([sexp(float(x),K,g) for x in xcore])
    ex=exact_dimless(xcore)
    minS=float(sc.min()); xmin=float(xcore[np.argmin(sc)])
    useful=ex>1e-8; useful5=ex>1e-5
    rel8=float(np.max(np.abs(sc[useful]-ex[useful])/ex[useful]))
    rel5=float(np.max(np.abs(sc[useful5]-ex[useful5])/ex[useful5]))
    maxabs=float(np.max(np.abs(sc-ex)))

    # Wider positivity scan; coupled Lindblad construction should stay >=0.
    wings=np.concatenate([
        -np.geomspace(1e4,12.001,3000),
        xcore,
        np.geomspace(20.001,1e4,3000),
    ])
    sw=np.array([sexp(float(x),K,g) for x in wings])
    minwide=float(sw.min()); xwide=float(wings[np.argmin(sw)])

    db=[]
    for xp in (.25,.5,1.,2.,3.,4.):
        spp=sexp(xp,K,g); smm=sexp(-xp,K,g)
        exactratio=math.exp(-BETA*fp.HBAR*wc*xp)
        ratio=smm/spp if spp>0 else math.inf
        logerr=abs(math.log(max(ratio,1e-300))-math.log(exactratio))
        db.append(logerr)
        print(f'DB p{N} x={xp:.2f} ratio={ratio:.12e} exact={exactratio:.12e} logerr={logerr:.6e}',flush=True)

    c0ex=exact_corr_norm(0,wc); c0c=cc(0,K,g)
    msg=(f'COUPLED_LINDBLAD_SDP p{N} relSDP={rel:.6e} GammaMin={eG.min():+.3e} '
         f'minSwide={minwide:+.3e} at={xwide:+.3e} maxrelS5={rel5:.6e} '
         f'maxrelS8={rel8:.6e} maxabsS={maxabs:.6e} db_logmax={max(db):.6e} '
         f'maxrelCpade={max(err_q):.6e} maxrelCexact={max(err_exact):.6e} '
         f'maxabsCexact={max(abs_exact):.6e} C0rel={abs(c0c-c0ex)/abs(c0ex):.6e}')
    print(msg,flush=True)
    print(f'::notice title=Experiment 03 coupled-Lindblad SDP::{msg}',flush=True)
    return dict(rel=rel,gmin=float(eG.min()),minS=minwide,relS5=rel5,
                relS8=rel8,db=max(db),cp=max(err_q),ce=max(err_exact),
                c0=abs(c0c-c0ex)/abs(c0ex))


def main():
    rows={N:audit(N) for N in (4,5,8)}
    print('SUMMARY')
    for N,m in rows.items():
        print(f'p{N} relSDP={m["rel"]:.3e} GammaMin={m["gmin"]:+.3e} '
              f'minS={m["minS"]:+.3e} spec5={m["relS5"]:.3e} '
              f'db={m["db"]:.3e} Cexact={m["ce"]:.3e} C0={m["c0"]:.3e}',flush=True)
    promising=[N for N,m in rows.items() if m['rel']<1e-2 and m['gmin']>-1e-7 and
               m['minS']>-1e-8 and m['c0']<1e-2]
    if promising:
        print('COUPLED_LINDBLAD_PADÉ_CORRECTION_PROMISING orders=' + ','.join(map(str,promising)))
    else:
        print('COUPLED_LINDBLAD_PADÉ_CORRECTION_NOT_YET_PROMISING')

if __name__=='__main__': main()
