#!/usr/bin/env python3
"""Persist the current low-R write screen and same-Y dark-bounce screen.

This is an auditability helper, not a new physics model.  It reruns a compact
subset of the already-defined calculations and writes one markdown snapshot so
important numerical values do not exist only in ephemeral GitHub Actions logs.
"""
from __future__ import annotations

import contextlib
import io
from pathlib import Path

from full_dynamic_rfsquid import DynamicForce
from nonlinear_fdt_twa_screen import run_case
from nonlinear_fdt_twa_convergence import wilson
import sameY_dissipative_bounce_screen as dark

OUT = Path('../RESULTS_LOW_R_DARK_2026-08-15.md')


def dark_text() -> str:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        dark.main()
    return buf.getvalue()


def write_text() -> str:
    model = DynamicForce(0.6, quick=False, Tmax=0.95)
    rows=[]
    # Compact final-decade screen. N=512 is for locating the turnover only;
    # high-statistics validation remains a separate workflow.
    for R in (5.0,10.0,15.0,20.0):
        for alpha in (0.80,0.90,1.00,1.20,1.50,2.00):
            o=run_case(model,8.0,R=R,alpha=alpha,ntraj=512,
                       dt_ps=0.5,seed=717171)
            n=int(o['ntraj']); k=int(o['n_right_final'])
            lo,hi=wilson(k,n)
            rows.append(
                f'R={R:g} ohm alpha={alpha:.2f}: '
                f'P_final={o["P_right_final"]:.6f} '
                f'CI95=[{lo:.6f},{hi:.6f}] fail={n-k}; '
                f'P_reform={o["P_xright_reform"]:.6f}; '
                f'coldReg=({o["cold_reg_x"]:.4f},{o["cold_reg_u"]:.4f}); '
                f'tauCold={o["tau_cold_ns"]:.5f} ns'
            )
    return '\n'.join(rows)


def main() -> None:
    text = '''# Experiment 03 — Persisted Low-R + Same-Y Dark Results — 2026-08-15

This file is generated by `calculations/persist_lowR_dark_results.py` to make
selected numerical outputs auditable in repository history.  The underlying
scientific caveats remain those of the source calculations.

## A. Final-decade nonlinear stationary-bath TWA/GLE write screen

```text
''' + write_text() + '''
```

These are semiclassical symmetrized-FDT TWA/GLE screening fractions, not exact
open-system quantum efficiencies.

## B. Same-Y cold dissipative-bounce screen

```text
''' + dark_text() + '''
```

The undamped full-potential WKB action is controlled.  The environmental action
increment is evaluated on the optimized sech^2 variational bounce and is a
first-order/variational same-Y screen, not the exact nonlocal dissipative bounce.
'''
    OUT.write_text(text,encoding='utf-8')
    print(f'wrote {OUT}')


if __name__=='__main__':
    main()
