#!/usr/bin/env python3
"""Matrix-free Schur-complement hierarchy closure for Experiment-03 Gate B.

This is a harmonic method-validation calculation, not detector capture.

For a retained HEOM hierarchy T, Vadimov (arXiv:2604.22568, Eq. 26)
defines the finite approximation

    L_T = L_TT - L_Tbar (L'_barbar)^(-1) L_barT,

where L'_barbar contains only the hierarchy-diagonal blocks of the discarded
tail.  Because QuTiP's bosonic HEOM couples only neighboring hierarchy labels,
only the immediately discarded tier D+1 is needed in this correction.

The correction is evaluated matrix-free at steady state.  This avoids forming
the dense cross-ADO blocks generated by the Schur product and avoids the
7,315-ADO brute-force N_Mats=16, depth=4 propagation used in the preceding
Gate-B convergence probe.

QuTiP is pinned to 5.3.0 in requirements-heom.txt.  This script intentionally
uses the private _grad_next/_grad_prev helpers of that pinned implementation so
that the Schur blocks are exactly the same blocks used to build QuTiP's HEOM
RHS.  Any QuTiP version change therefore requires revalidation of this script.
"""
from __future__ import annotations

import argparse
import math
import time
from collections import defaultdict

import numpy as np
import scipy.sparse.linalg as spla

import full_dynamic_rfsquid as fd
from finite_time_basin_slice import cold_phase_scale
from quantum_initial_capture import PHI_BAR
from two_pole_joint_covariance import covariance_matrix
from heom_harmonic_port_validation import (
    HBAR, R, G, WD, L, C, DELTA, ALPHA, bath_expansion,
)

from qutip import destroy, qeye
from qutip.solver.heom import BosonicBath, HEOMSolver


CASES = {
    # Depth trend at a bath truncation that was already accurate in time-domain
    # probes.  The d=1 point is intentionally cheap and is a convergence anchor.
    "n8d1": dict(dim=6, nmats=8, depth=1),
    "n8d2": dict(dim=6, nmats=8, depth=2),
    # Independent system-Hilbert convergence at the same hierarchy/bath order.
    "n8d2_dim8": dict(dim=8, nmats=8, depth=2),
    # Independent Matsubara convergence at fixed d=2.
    "n16d2": dict(dim=6, nmats=16, depth=2),
}


def _allowed_tail_step(exp, occupation: int) -> bool:
    """Whether an unretained D+1 label may contain occupation+1 for exp."""
    # For ordinary bosonic exponents exp.dim is None (unbounded).  Respect an
    # explicit finite exponent dimension if one is ever supplied.
    return exp.dim is None or occupation + 1 < exp.dim


def _rho_diagnostics(x, dim, xop, uop, target_x, target_u):
    sup = dim * dim
    rho = np.asarray(x[:sup]).reshape((dim, dim), order="F")
    anti = np.linalg.norm(rho - rho.conj().T) / max(
        np.linalg.norm(rho + rho.conj().T), 1e-300
    )
    rhoh = 0.5 * (rho + rho.conj().T)
    tr = float(np.real(np.trace(rhoh)))
    rhon = rhoh / tr
    X = xop.full()
    U = uop.full()
    mx = float(np.real(np.trace(rhon @ X)))
    mu = float(np.real(np.trace(rhon @ U)))
    x2 = float(np.real(np.trace(rhon @ (X @ X))))
    u2 = float(np.real(np.trace(rhon @ (U @ U))))
    sx = math.sqrt(max(x2 - mx * mx, 0.0))
    su = math.sqrt(max(u2 - mu * mu, 0.0))
    eigmin = float(np.linalg.eigvalsh(rhon).min())
    top = float(np.real(rhon[-1, -1]))
    return dict(
        sx=sx,
        su=su,
        relx=sx / target_x - 1.0,
        relu=su / target_u - 1.0,
        trace=tr,
        antiherm=anti,
        eigmin=eigmin,
        top=top,
    )


def run_case(name: str) -> None:
    cfg = CASES[name]
    ob, ot = fd.BETA_COLD, fd.DELTA_TILT
    original = fd.CASES[.6]
    try:
        fd.BETA_COLD = .80
        fd.DELTA_TILT = DELTA
        fd.CASES[.6] = (L, C, original[2])
        model = fd.DynamicForce(.6, quick=False, Tmax=1.02)

        M = covariance_matrix(model, .6, R, ALPHA, y_min=-22, y_max=22)
        target_x = math.sqrt(M[0, 0])
        target_u = math.sqrt(M[1, 1])
        _xc, _kappa, wc = cold_phase_scale(model, .6)

        dim = cfg["dim"]
        nmats = cfg["nmats"]
        depth = cfg["depth"]
        sup = dim * dim

        sigma0 = math.sqrt(HBAR / (2 * C * PHI_BAR**2 * wc))
        a = destroy(dim)
        n = a.dag() * a
        xop = sigma0 * (a + a.dag())
        uop = 1j * sigma0 * (a.dag() - a)
        H = n + 0.5 * qeye(dim)

        ct_phys = PHI_BAR**2 / HBAR * G * WD / (2 * math.sqrt(2))
        ct_scaled = ct_phys / wc
        H = H + ct_scaled * (xop * xop)

        cr, vr, ci, vi = bath_expansion(wc, nmats)
        bath = BosonicBath(
            xop, cr, vr, ci, vi, combine=True, tag="direct-port"
        )
        solver = HEOMSolver(
            H,
            bath,
            max_depth=depth,
            options={"progress_bar": "", "store_states": False},
        )

        labels = solver.ados.labels
        nado = len(labels)
        nexp = len(solver.ados.exponents)
        size = nado * sup
        Ltt = solver.rhs(0).to("CSR").data.as_scipy().tocsr()
        Lsys = solver.L_sys(0).to("CSR").data.as_scipy().toarray()

        # Build the D+1 boundary graph.  Each discarded label can connect to
        # several retained top-tier labels.  Keeping all predecessors is
        # essential: the Schur product generates cross-ADO couplings between
        # retained labels that share the same discarded neighbor.
        edges = defaultdict(list)
        top_labels = [lab for lab in labels if sum(lab) == depth]
        for lab in top_labels:
            retained_idx = solver.ados.idx(lab)
            for k, exp in enumerate(solver.ados.exponents):
                if not _allowed_tail_step(exp, lab[k]):
                    continue
                tail = list(lab)
                tail[k] += 1
                tail = tuple(tail)
                A = solver._grad_next(lab, k).as_scipy().tocsr()
                B = solver._grad_prev(tail, k).as_scipy().tocsr()
                edges[tail].append((retained_idx, A, B))

        # L'_tail,tail = L_sys - (sum_k n_k v_k) I.  Pre-invert these small
        # system-superoperator blocks.  This is far cheaper than materializing
        # the dense retained-ADO Schur matrix.
        eye_sup = np.eye(sup, dtype=complex)
        tail_inv = {}
        t_build = time.perf_counter()
        for tail in edges:
            decay = sum(tail[k] * solver.ados.vk[k] for k in range(nexp))
            D = Lsys - decay * eye_sup
            tail_inv[tail] = np.linalg.inv(D)
        build_s = time.perf_counter() - t_build

        edge_count = sum(len(v) for v in edges.values())
        cross_block_count = sum(len(v) ** 2 for v in edges.values())
        print(
            f"CASE={name} dim={dim} nmats={nmats} depth={depth} "
            f"nexp={nexp} nado={nado} retained_size={size} "
            f"tail_labels={len(edges)} boundary_edges={edge_count} "
            f"schur_cross_blocks={cross_block_count} inv_build_s={build_s:.3f}",
            flush=True,
        )
        print(
            f"target_sigma_x={target_x:.10e} target_sigma_u={target_u:.10e} "
            f"ct/wc={ct_scaled:.10e}",
            flush=True,
        )

        def schur_mv(vec):
            vec = np.asarray(vec, dtype=complex)
            out = np.asarray(Ltt @ vec, dtype=complex)
            # - L_Tbar D_tail^{-1} L_barT
            for tail, links in edges.items():
                source = np.zeros(sup, dtype=complex)
                for retained_idx, _A, B in links:
                    sl = slice(retained_idx * sup, (retained_idx + 1) * sup)
                    source += B @ vec[sl]
                feedback = tail_inv[tail] @ source
                for retained_idx, A, _B in links:
                    sl = slice(retained_idx * sup, (retained_idx + 1) * sup)
                    out[sl] -= A @ feedback
            return out

        # Replace one physical-density equation by Tr rho_0 = 1, matching the
        # standard QuTiP HEOM steady-state gauge fixing.
        trace_idx = np.array([j * (dim + 1) for j in range(dim)], dtype=int)

        def constrained_mv(vec):
            out = schur_mv(vec)
            out[0] = np.sum(np.asarray(vec)[trace_idx])
            return out

        Aop = spla.LinearOperator((size, size), matvec=constrained_mv,
                                  dtype=np.complex128)
        b = np.zeros(size, dtype=complex)
        b[0] = 1.0

        # Zero-tail truncation is both a baseline and a strong preconditioner.
        A0 = Ltt.tolil(copy=True)
        A0.rows[0] = trace_idx.tolist()
        A0.data[0] = [1.0 + 0j] * dim
        lu = spla.splu(A0.tocsc())
        x_zero = lu.solve(b)
        Mpre = spla.LinearOperator((size, size), matvec=lu.solve,
                                   dtype=np.complex128)

        zero = _rho_diagnostics(
            x_zero, dim, xop, uop, target_x, target_u
        )
        print(
            "ZERO "
            f"relx={zero['relx']:+.6e} relu={zero['relu']:+.6e} "
            f"trace={zero['trace']:.12f} antiherm={zero['antiherm']:.3e} "
            f"eigmin={zero['eigmin']:.6e} topPop={zero['top']:.6e}",
            flush=True,
        )

        hist = []
        t_solve = time.perf_counter()
        x, info = spla.gmres(
            Aop,
            b,
            x0=x_zero,
            M=Mpre,
            rtol=2e-10,
            atol=2e-12,
            restart=80,
            maxiter=500,
            callback=lambda r: hist.append(float(r)),
            callback_type="pr_norm",
        )
        solve_s = time.perf_counter() - t_solve
        residual = np.linalg.norm(constrained_mv(x) - b) / np.linalg.norm(b)
        q = _rho_diagnostics(x, dim, xop, uop, target_x, target_u)
        final_err = max(abs(q["relx"]), abs(q["relu"]))
        zero_err = max(abs(zero["relx"]), abs(zero["relu"]))
        shift = max(
            abs(q["sx"] - zero["sx"]) / target_x,
            abs(q["su"] - zero["su"]) / target_u,
        )

        msg = (
            f"CASE={name} SCHUR FINAL relx={q['relx']:+.6e} "
            f"relu={q['relu']:+.6e} max_cov_error={final_err:.6e} "
            f"zero_cov_error={zero_err:.6e} closure_shift={shift:.6e} "
            f"trace={q['trace']:.12f} antiherm={q['antiherm']:.3e} "
            f"eigmin={q['eigmin']:.6e} topPop={q['top']:.6e} "
            f"gmres_info={info} gmres_steps={len(hist)} residual={residual:.3e} "
            f"solve_s={solve_s:.3f}"
        )
        print(msg, flush=True)
        print(
            f"::notice title=Experiment 03 Schur HEOM closure::{msg}",
            flush=True,
        )

        # Gross guards only.  The Gate-B pass/fail threshold is assessed across
        # the full closure matrix after all independent CI jobs complete.
        if info != 0:
            raise RuntimeError(f"Schur HEOM GMRES did not converge: info={info}")
        if residual > 2e-8:
            raise RuntimeError("Schur HEOM constrained residual too large")
        if abs(q["trace"] - 1.0) > 2e-8:
            raise RuntimeError("Schur HEOM trace failure")
        if q["antiherm"] > 2e-7:
            raise RuntimeError("Schur HEOM steady state is materially non-Hermitian")
        if final_err > .05:
            raise RuntimeError("Schur HEOM harmonic covariance misses FDT by >5%")
        if q["eigmin"] < -5e-3:
            raise RuntimeError("Schur HEOM has gross density-matrix negativity")
        print("PASS_PROBE", flush=True)
    finally:
        fd.BETA_COLD = ob
        fd.DELTA_TILT = ot
        fd.CASES[.6] = original


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", choices=sorted(CASES), required=True)
    args = ap.parse_args()
    run_case(args.case)


if __name__ == "__main__":
    main()
