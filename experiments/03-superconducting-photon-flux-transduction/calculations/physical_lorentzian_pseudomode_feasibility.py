#!/usr/bin/env python3
"""Physical independent-pseudomode feasibility fit for the exact direct-port bath.

This is deliberately *not* the rejected Padé->pseudomode shortcut.  The target
is the exact physical unsymmetrized direct-port spectrum.  The dictionary is a
nonnegative mixture of spectra generated by damped positive-frequency bosonic
modes at the physical bath temperature:

  C_j(tau) = q_j [(n_j+1) exp(-(g_j+i O_j)tau)
                  + n_j exp(-(g_j-i O_j)tau)],      q_j >= 0,

  n_j = 1/(exp(theta O_j)-1),   theta=beta*hbar*omega_c.

The corresponding dimensionless spectrum is

  s_j(x)=q_j [ 2 g_j(n_j+1)/((x-O_j)^2+g_j^2)
               +2 g_j n_j/((x+O_j)^2+g_j^2) ],

which is globally nonnegative and has a completely positive independent-mode
Lindblad interpretation.  Finite linewidth means this local thermal model does
not enforce exact KMS frequency-by-frequency, so detailed-balance error is
measured explicitly rather than assumed away.

A large nonnegative dictionary is fitted by bounded least squares, then the
largest correlation-weight modes are retained and refitted for K=8,16,32,64.
The point is feasibility: can a modest *physical* mode count reproduce both the
system-relevant exact spectrum and the exact 0--24 tau correlation before any
system dynamics are attempted?

No Gate-C result is produced.  A successful fit would still require independent
harmonic FDT validation and pseudomode Fock/mode-count convergence.
"""
from __future__ import annotations

import math
import numpy as np
from scipy.optimize import lsq_linear

from direct_port_bath_correlation import (
    HBAR, KB, T0, BETA, FC, G, corr_quad,
)

WC=2*math.pi*FC
S0=2*G/BETA
THETA=BETA*HBAR*WC


def exact_s(x):
    """Stable exact physical S^>(omega)/S(0) for signed x=omega/omega_c."""
    a=np.asarray(x,float)
    out=np.empty_like(a)
    z=np.abs(a)<1e-15
    out[z]=1.0
    nz=~z
    if np.any(nz):
        w=WC*a[nz]
        # Stable direct formula using signed y; J is odd.
        aw=np.abs(w)
        Jabs=HBAR*G*aw*(0.9*WC)**4/(aw**4+(0.9*WC)**4)
        y=BETA*HBAR*aw
        sp=2*Jabs/(-np.expm1(-np.minimum(y,700.0)))
        vals=np.where(w>=0,sp,sp*np.exp(-np.minimum(y,745.0)))
        out[nz]=vals/S0
    return out


def dictionary():
    # Dense where the physical system has appreciable transitions, sparse in the
    # far positive tail.  All centers are positive, preserving a bounded
    # pseudomode Hamiltonian.
    O=np.unique(np.concatenate([
        np.geomspace(0.01,0.20,16),
        np.arange(0.20,4.001,0.10),
        np.arange(4.25,8.01,0.25),
        np.arange(8.5,16.01,0.5),
        np.arange(17.0,25.1,1.0),
    ]))
    gam=np.array([0.025,0.05,0.10,0.20,0.40,0.80,1.60])
    modes=[(float(o),float(g)) for o in O for g in gam]
    return modes


def samples():
    core=np.linspace(-8,16,1601)
    pos=np.geomspace(16.01,1e3,320)
    neg=-np.geomspace(8.01,1e3,280)[::-1]
    return np.concatenate([neg,core,pos])


def basis_column(x,O,g):
    n=1/np.expm1(THETA*O)
    return (2*g*(n+1)/((x-O)**2+g*g)
            +2*g*n/((x+O)**2+g*g))


def design(x,modes):
    A=np.empty((len(x),len(modes)),float)
    for j,(O,g) in enumerate(modes):
        A[:,j]=basis_column(x,O,g)
    return A


def fit_nonnegative(A,y,weights):
    Aw=A*weights[:,None]; yw=y*weights
    sol=lsq_linear(Aw,yw,bounds=(0,np.inf),method='trf',tol=2e-12,
                   lsmr_tol='auto',max_iter=500,verbose=0)
    if not sol.success:
        print(f'LSQ_WARNING success={sol.success} status={sol.status} message={sol.message}',flush=True)
    return np.maximum(sol.x,0.0),sol.cost,sol.optimality


def spectrum_from(q,A): return A@q


def corr_fit(tau,modes,q):
    out=0j
    for (O,g),qq in zip(modes,q):
        if qq==0: continue
        n=1/np.expm1(THETA*O)
        out += qq*((n+1)*np.exp(-(g+1j*O)*tau)
                   +n*np.exp(-(g-1j*O)*tau))
    # q has normalization such that C/(S0*WC) equals this expression.
    return out


def corr_exact_norm(tau):
    return corr_quad(float(tau)/WC)/(S0*WC)


def metrics(tag,modes,q,x_eval,A_eval,y_eval):
    sf=A_eval@q
    abs_err=np.abs(sf-y_eval)
    useful=y_eval>1e-8
    useful2=y_eval>1e-5
    maxrel=float(np.max(abs_err[useful]/y_eval[useful])) if np.any(useful) else math.nan
    maxrel2=float(np.max(abs_err[useful2]/y_eval[useful2])) if np.any(useful2) else math.nan
    maxabs=float(np.max(abs_err))
    rms=float(np.sqrt(np.mean(abs_err**2)))
    negmin=float(np.min(sf))

    # Detailed-balance error at system-relevant signed frequencies.
    db=[]
    for xp in (.25,.5,1.,2.,3.,4.):
        sp=float(np.dot(np.array([basis_column(np.array([xp]),*m)[0] for m in modes]),q))
        sm=float(np.dot(np.array([basis_column(np.array([-xp]),*m)[0] for m in modes]),q))
        exact_ratio=math.exp(-THETA*xp)
        ratio=sm/sp if sp>0 else math.inf
        # log-ratio error is meaningful over many decades.
        logerr=abs(math.log(max(ratio,1e-300))-math.log(exact_ratio))
        db.append(logerr)
        print(f'DB {tag} x={xp:.2f} ratio={ratio:.12e} exact={exact_ratio:.12e} logerr={logerr:.6e}',flush=True)
    dbmax=max(db)

    taus=np.array([0.,.1,.25,.5,1.,2.,4.,8.,12.,16.,20.,24.])
    cerr=[]; cabs=[]
    for tau in taus:
        ce=corr_exact_norm(tau); cf=corr_fit(tau,modes,q)
        rel=abs(cf-ce)/max(abs(ce),1e-14)
        cerr.append(rel); cabs.append(abs(cf-ce))
        print(f'CORR {tag} tau={tau:5.2f} fit=({cf.real:+.12e}{cf.imag:+.12e}j) '
              f'exact=({ce.real:+.12e}{ce.imag:+.12e}j) rel={rel:.6e}',flush=True)

    active=int(np.sum(q>1e-12*np.max(q))) if np.max(q)>0 else 0
    c0fit=corr_fit(0.,modes,q); c0ex=corr_exact_norm(0.)
    msg=(f'PHYSICAL_LORENTZ_FIT {tag} modes={len(modes)} active={active} '
         f'maxabsS={maxabs:.6e} rmsS={rms:.6e} maxrelS_gt1e-8={maxrel:.6e} '
         f'maxrelS_gt1e-5={maxrel2:.6e} minS={negmin:.3e} db_logmax={dbmax:.6e} '
         f'maxrelC={max(cerr):.6e} maxabsC={max(cabs):.6e} '
         f'C0rel={abs(c0fit-c0ex)/abs(c0ex):.6e}')
    print(msg,flush=True)
    print(f'::notice title=Experiment 03 physical Lorentzian feasibility::{msg}',flush=True)
    return dict(maxabs=maxabs,rms=rms,maxrel=maxrel,maxrel2=maxrel2,
                db=dbmax,corr=max(cerr),c0=abs(c0fit-c0ex)/abs(c0ex),active=active)


def main():
    modes=dictionary(); x=samples(); y=exact_s(x)
    A=design(x,modes)
    # Hybrid weighting: accurate relative fit where the spectrum matters, but a
    # floor prevents the exponentially tiny negative-frequency tail from
    # dominating the least-squares objective.
    floor=1e-7
    weights=1/np.sqrt(np.maximum(y,floor))
    q,cost,opt=fit_nonnegative(A,y,weights)
    print(f'FULL_DICTIONARY modes={len(modes)} cost={cost:.12e} optimality={opt:.12e} '
          f'nonzero={np.sum(q>1e-14*np.max(q))}',flush=True)

    xe=np.concatenate([np.linspace(-8,16,4801),np.geomspace(16.01,1e3,600)])
    ye=exact_s(xe); Ae=design(xe,modes)
    full=metrics('FULL',modes,q,xe,Ae,ye)

    # Rank by contribution to C(0), q*(2n+1), which is a more physical measure
    # than raw q when low-frequency thermal occupations are large.
    score=np.empty(len(modes))
    for j,(O,g) in enumerate(modes):
        n=1/np.expm1(THETA*O); score[j]=q[j]*(2*n+1)
    order=np.argsort(score)[::-1]

    results=[]
    for K in (8,16,32,64):
        idx=order[:K]
        mk=[modes[i] for i in idx]
        Ak=A[:,idx]
        qk,costk,optk=fit_nonnegative(Ak,y,weights)
        Aek=Ae[:,idx]
        print(f'REFIT K={K} cost={costk:.12e} optimality={optk:.12e}',flush=True)
        met=metrics(f'K{K}',mk,qk,xe,Aek,ye); results.append((K,met))

    print('SUMMARY')
    for K,m in results:
        print(f'K={K:2d} maxrelS_gt1e-5={m["maxrel2"]:.6e} db_logmax={m["db"]:.6e} '
              f'maxrelC={m["corr"]:.6e} C0rel={m["c0"]:.6e} active={m["active"]}',flush=True)

    # Feasibility only.  This intentionally does not hard-fail if a modest mode
    # count is inadequate; inadequacy is a scientific result.
    viable=[K for K,m in results if m['maxrel2']<5e-2 and m['corr']<5e-2 and m['c0']<1e-2]
    if viable:
        print('PHYSICAL_LORENTZIAN_FEASIBLE modest_K=' + ','.join(map(str,viable)))
    else:
        print('PHYSICAL_LORENTZIAN_NOT_FEASIBLE_AT_TESTED_MODE_COUNTS')

if __name__=='__main__': main()
